const assert=require('assert');
const L=require('./fret_label_model.js');
let wires=[];
for(const [n,x] of [[0,0],[1,100],[2,190],[3,270]]) wires=L.add(wires,{xt:x,xb:x},n);
wires=L.remove(wires,1);
assert.deepStrictEqual(wires.map(L.number),[0,2,3]);
assert.deepStrictEqual(L.cells(wires).map(([a,b])=>L.number(b)),[3]);
wires=L.add(wires,{xt:100,xb:100},1);
assert.deepStrictEqual(wires.map(L.number),[0,1,2,3]);
assert.throws(()=>L.add(wires,{xt:123},2));
console.log('Physical fret deletion, reinsertion, gap cells and duplicate rejection: OK');
